create schema if not exists ppm;
set search_path to ppm;

-- ---------------------------------------------------------------------
-- Master data
-- ---------------------------------------------------------------------
create table item_type (
    item_type_id   integer generated by default as identity primary key,
    type_code      varchar(20)  not null unique,
    type_name      varchar(100) not null
);

create table item (
    item_id              integer generated by default as identity primary key,
    item_type_id         integer      not null references item_type (item_type_id),
    item_code            varchar(50)  not null unique,
    item_name            varchar(150) not null,
    description          text,
    base_unit_of_measure varchar(20)  not null
);

create table bom_component (
    bom_component_id   integer generated by default as identity primary key,
    parent_item_id     integer       not null references item (item_id),
    component_item_id  integer       not null references item (item_id),
    quantity_per       numeric(12,4) not null check (quantity_per > 0),
    unique (parent_item_id, component_item_id),
    check (parent_item_id <> component_item_id)          -- an item cannot contain itself
);

create table operation (
    operation_id    integer generated by default as identity primary key,
    operation_name  varchar(100) not null,
    description     text
);

create table employee (
    employee_id    integer generated by default as identity primary key,
    employee_name  varchar(150) not null,
    role           varchar(50)  not null
);

create table defect_code (
    defect_code  varchar(20) primary key,
    description  text        not null,
    category     varchar(50),
    severity     varchar(20)
);

-- ---------------------------------------------------------------------
-- Routings
-- ---------------------------------------------------------------------
create table routing (
    routing_id      integer generated by default as identity primary key,
    item_id         integer     not null references item (item_id),
    revision_no     varchar(10) not null,
    effective_date  date        not null,
    obsolete_date   date,
    routing_status  varchar(20) not null,
    unique (item_id, revision_no),
    check (obsolete_date is null or obsolete_date >= effective_date)
);

create table routing_step (
    routing_step_id      integer generated by default as identity primary key,
    routing_id           integer not null references routing (routing_id),
    operation_id         integer not null references operation (operation_id),
    sequence_no          integer not null check (sequence_no > 0),
    requires_inspection  boolean not null default false,
    unique (routing_id, sequence_no)
);

-- ---------------------------------------------------------------------
-- Sales and production orders
-- ---------------------------------------------------------------------
create table sales_order (
    sales_order_id  integer generated by default as identity primary key,
    customer_name   varchar(150) not null,
    order_date      date         not null,
    order_status    varchar(20)  not null
);

create table sales_order_line (
    sales_order_line_id  integer generated by default as identity primary key,
    sales_order_id       integer       not null references sales_order (sales_order_id),
    item_id              integer       not null references item (item_id),
    quantity_ordered     numeric(12,2) not null check (quantity_ordered > 0)
);

create table production_order (
    production_order_id  integer generated by default as identity primary key,
    routing_id           integer       not null references routing (routing_id),
    quantity_planned     numeric(12,2) not null check (quantity_planned > 0),
    release_date         date,
    order_status         varchar(20)   not null
);

create table production_allocation (
    production_allocation_id  integer generated by default as identity primary key,
    sales_order_line_id       integer       not null references sales_order_line (sales_order_line_id),
    production_order_id       integer       not null references production_order (production_order_id),
    allocated_quantity        numeric(12,2) not null check (allocated_quantity > 0),
    unique (sales_order_line_id, production_order_id)
);

-- ---------------------------------------------------------------------
-- Shop-floor execution (structure only; leave empty for this assignment)
-- ---------------------------------------------------------------------
create table production_item (
    production_item_id   integer generated by default as identity primary key,
    production_order_id  integer     not null references production_order (production_order_id),
    barcode              varchar(50) not null unique
);

create table operation_activity (
    activity_id               integer generated by default as identity primary key,
    production_item_id        integer not null references production_item (production_item_id),
    routing_step_id           integer not null references routing_step (routing_step_id),
    employee_id               integer not null references employee (employee_id),
    rework_authorization_id   integer,               -- FK added below (circular reference)
    attempt_no                integer not null default 1 check (attempt_no > 0),
    start_time                timestamptz,
    end_time                  timestamptz,
    activity_status           varchar(20) not null,
    unique (production_item_id, routing_step_id, attempt_no),
    check (attempt_no = 1 or rework_authorization_id is not null),   -- rework attempts need authorization
    check (end_time is null or start_time is null or end_time >= start_time)
);

create table inspection (
    inspection_id    integer generated by default as identity primary key,
    activity_id      integer     not null references operation_activity (activity_id),
    inspector_id     integer     not null references employee (employee_id),
    inspection_time  timestamptz not null,
    result           varchar(4)  not null check (result in ('Pass', 'Fail'))
);

create table inspection_defect (
    inspection_defect_id  integer generated by default as identity primary key,
    inspection_id         integer     not null references inspection (inspection_id),
    defect_code           varchar(20) not null references defect_code (defect_code),
    unique (inspection_id, defect_code)
);

create table rework_authorization (
    rework_authorization_id     integer generated by default as identity primary key,
    inspection_id               integer     not null unique references inspection (inspection_id),
    supervisor_id               integer     not null references employee (employee_id),
    return_to_routing_step_id   integer     not null references routing_step (routing_step_id),
    authorized_time             timestamptz not null,
    instructions                text
);

alter table operation_activity
    add constraint operation_activity_rework_authorization_fk
    foreign key (rework_authorization_id) references rework_authorization (rework_authorization_id);

create table correction (
    correction_id               integer generated by default as identity primary key,
    activity_id                 integer references operation_activity (activity_id),
    inspection_id               integer references inspection (inspection_id),
    corrected_by_employee_id    integer     not null references employee (employee_id),
    correction_time             timestamptz not null,
    correction_type             varchar(30) not null,
    field_name                  varchar(100),
    old_value                   text,
    new_value                   text,
    reason                      text        not null,
    reverses_correction_id      integer references correction (correction_id),
    check (num_nonnulls(activity_id, inspection_id) = 1)   -- exactly one of activity / inspection
);
